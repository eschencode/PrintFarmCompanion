    service (Art. 6(1)(f) GDPR).
  </li>
  <li>
    <strong>Usage analysis to improve the service</strong> — we analyse how the
    service is used (e.g. which features are used, error rates) to improve it.
    Legal basis: legitimate interest (Art. 6(1)(f) GDPR).
  </li>
  <li>
    <strong>Aggregated, anonymised statistics</strong> — we create aggregated,
    anonymised statistics from usage and workspace content (for example,
    industry-level printing and product trends). These statistics do not contain
    personal data and cannot be traced back to you or your workspace; once
    anonymised, they are outside the scope of the GDPR. We may use such
    statistics commercially, including sharing industry insights with third
    parties.
  </li>
